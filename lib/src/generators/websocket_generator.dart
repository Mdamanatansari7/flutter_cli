/// Pure logic for the WebSocket Service Generator: client-kind
/// selection and Dart code generation for a complete, reusable,
/// singleton WebSocket service. No file I/O here on purpose — the CLI
/// orchestration layer (`ninjadev_cli.dart`) reads/writes files and
/// calls into this class.
library;

/// Which WebSocket implementation the generated code should use.
enum SocketClientKind {
  /// `package:web_socket_channel` — works on mobile, desktop and web.
  webSocketChannel,

  /// Built-in `dart:io` WebSocket — no extra dependency, but no web
  /// support.
  dartIo,
}

/// Everything the user chose in the wizard.
class SocketServiceConfig {
  const SocketServiceConfig({
    required this.clientKind,
    required this.baseName,
    this.url = '',
    this.envKey,
    this.heartbeatSeconds = 30,
    this.maxReconnectAttempts = 5,
  });

  final SocketClientKind clientKind;

  /// Lowercase base name, e.g. `chat` -> class `ChatService` and file
  /// `chat_service.dart`.
  final String baseName;

  /// Literal socket URL (`ws://`/`wss://`), or '' when [envKey] is set.
  final String url;

  /// `.env` variable holding the socket URL (e.g. `SOCKET_URL`).
  final String? envKey;

  /// Heartbeat ping interval in seconds; <= 0 disables heartbeats.
  final int heartbeatSeconds;

  /// Maximum automatic reconnect attempts after a drop; <= 0 disables
  /// auto-reconnect.
  final int maxReconnectAttempts;

  bool get usesEnv => envKey != null && envKey!.isNotEmpty;

  bool get needsDotenv => usesEnv;

  bool get needsWebSocketChannel =>
      clientKind == SocketClientKind.webSocketChannel;

  /// `chat` -> `ChatService`.
  String get className => '${_pascal(baseName)}Service';

  /// The exact Dart expression resolving the default socket URL:
  /// either a quoted literal or a `.env` lookup.
  String get urlExpression => usesEnv
      ? "dotenv.env['$envKey'] ?? ''"
      : "'$url'";
}

class WebSocketGenerator {
  WebSocketGenerator._();

  /// Generates the complete, self-contained service file for [config]:
  /// singleton access, connect/send/disconnect, a broadcast messages
  /// stream, heartbeat pings and automatic reconnection.
  static String generate(SocketServiceConfig config) {
    final channel = config.needsWebSocketChannel;
    final b = StringBuffer();

    // --- imports (canonical order: dart: first, then package:) ---
    b.writeln("import 'dart:async';");
    b.writeln("import 'dart:convert';");
    if (!channel) b.writeln("import 'dart:io';");
    b.writeln();
    b.writeln("import 'package:flutter/foundation.dart';");
    if (config.needsDotenv) {
      b.writeln("import 'package:flutter_dotenv/flutter_dotenv.dart';");
    }
    if (channel) {
      b.writeln(
          "import 'package:web_socket_channel/web_socket_channel.dart';");
    }
    b.writeln();

    b.writeln('/// Reusable WebSocket service generated by NinjaDev — use');
    b.writeln('/// `static final ${config.className}.instance` anywhere in the app.');
    b.writeln('class ${config.className} {');
    b.writeln('  ${config.className}._();');
    b.writeln(
        '  static final ${config.className} instance = ${config.className}._();');
    b.writeln();
    b.writeln(
        '  static const int heartbeatSeconds = ${config.heartbeatSeconds};');
    b.writeln(
        '  static const int maxReconnectAttempts = ${config.maxReconnectAttempts};');
    b.writeln();
    b.writeln('  ${channel ? 'WebSocketChannel' : 'WebSocket'}? _socket;');
    b.writeln('  StreamSubscription<dynamic>? _subscription;');
    b.writeln('  Timer? _heartbeatTimer;');
    b.writeln('  final _messages = StreamController<dynamic>.broadcast();');
    b.writeln('  final _status = StreamController<String>.broadcast();');
    b.writeln('  bool _connected = false;');
    b.writeln('  int _reconnectCount = 0;');
    b.writeln('  String? _lastUrl;');
    b.writeln();
    b.writeln('  /// Decoded incoming messages (JSON maps/lists or raw text).');
    b.writeln('  Stream<dynamic> get messages => _messages.stream;');
    b.writeln();
    b.writeln('  /// Lifecycle events: `connecting`, `connected`,');
    b.writeln('  /// `disconnected`, `reconnecting`, `error`.');
    b.writeln('  Stream<String> get status => _status.stream;');
    b.writeln();
    b.writeln('  /// True while the socket is connected.');
    b.writeln('  bool get isConnected => _connected;');
    b.writeln();
    b.writeln('  /// Connects to the socket URL. Pass [url] to override the');
    b.writeln('  /// default (configured literal or `.env` variable). For');
    b.writeln('  /// auth tokens, include them in the URL (browsers don\'t');
    b.writeln('  /// allow custom WebSocket headers).');
    b.writeln('  Future<void> connect({String? url}) async {');
    b.writeln('    await disconnect();');
    b.writeln('    final finalUrl = url ?? ${config.urlExpression};');
    b.writeln('    if (finalUrl.isEmpty) {');
    b.writeln('      throw Exception(');
    if (config.usesEnv) {
      b.writeln(
          "        'Socket URL is not configured. Set ${config.envKey} in .env or pass a url.',");
    } else {
      b.writeln(
          "        'Socket URL is not configured. Pass a url to connect().',");
    }
    b.writeln('      );');
    b.writeln('    }');
    b.writeln('    _lastUrl = finalUrl;');
    b.writeln('    _reconnectCount = 0;');
    b.writeln('    await _openSocket(finalUrl);');
    b.writeln('  }');
    b.writeln();
    _writeOpenSocket(b, config);
    b.writeln();
    b.writeln('  void _onData(dynamic data) {');
    b.writeln('    if (data is String && data.trim().isNotEmpty) {');
    b.writeln('      try {');
    b.writeln('        _messages.add(jsonDecode(data));');
    b.writeln('      } on FormatException {');
    b.writeln('        _messages.add(data);');
    b.writeln('      }');
    b.writeln('    } else {');
    b.writeln('      _messages.add(data);');
    b.writeln('    }');
    b.writeln('  }');
    b.writeln();
    b.writeln('  void _onError(Object error) {');
    b.writeln('    _connected = false;');
    b.writeln("    debugPrint('Socket error: \$error');");
    b.writeln("    _status.add('error');");
    b.writeln('    _scheduleReconnect();');
    b.writeln('  }');
    b.writeln();
    b.writeln('  void _onDone() {');
    b.writeln('    _connected = false;');
    b.writeln('    _stopHeartbeat();');
    b.writeln("    _status.add('disconnected');");
    b.writeln('    _scheduleReconnect();');
    b.writeln('  }');
    b.writeln();
    b.writeln('  void _scheduleReconnect() {');
    b.writeln('    if (maxReconnectAttempts <= 0) return;');
    b.writeln('    if (_reconnectCount >= maxReconnectAttempts) {');
    b.writeln('      _reconnectCount = 0;');
    b.writeln("      _status.add('error');");
    b.writeln('      debugPrint(');
    b.writeln(
        '        \'Socket reconnection failed after \$maxReconnectAttempts attempts\',');
    b.writeln('      );');
    b.writeln('      return;');
    b.writeln('    }');
    b.writeln('    _reconnectCount++;');
    b.writeln("    _status.add('reconnecting');");
    b.writeln('    Future.delayed(const Duration(seconds: 3), () {');
    b.writeln('      if (_lastUrl == null) return;');
    b.writeln('      _openSocket(_lastUrl!);');
    b.writeln('    });');
    b.writeln('  }');
    b.writeln();
    b.writeln('  void _startHeartbeat() {');
    b.writeln('    _stopHeartbeat();');
    b.writeln('    if (heartbeatSeconds <= 0) return;');
    b.writeln('    _heartbeatTimer = Timer.periodic(');
    b.writeln('      Duration(seconds: heartbeatSeconds),');
    b.writeln('      (_) {');
    b.writeln('        try {');
    if (channel) {
      b.writeln(
          "          _socket?.sink.add(jsonEncode({'type': 'ping'}));");
    } else {
      b.writeln("          _socket?.add(jsonEncode({'type': 'ping'}));");
    }
    b.writeln('        } catch (_) {}');
    b.writeln('      },');
    b.writeln('    );');
    b.writeln('  }');
    b.writeln();
    b.writeln('  void _stopHeartbeat() {');
    b.writeln('    _heartbeatTimer?.cancel();');
    b.writeln('    _heartbeatTimer = null;');
    b.writeln('  }');
    b.writeln();
    b.writeln('  /// Sends a message — JSON for maps/lists, raw text for strings.');
    b.writeln('  void send(dynamic data) {');
    b.writeln('    final socket = _socket;');
    b.writeln('    if (socket == null) {');
    b.writeln("      throw Exception('Socket is not connected. Call connect() first.');");
    b.writeln('    }');
    b.writeln('    if (data is String) {');
    b.writeln('      socket${channel ? '.sink' : ''}.add(data);');
    b.writeln('    } else {');
    b.writeln('      socket${channel ? '.sink' : ''}.add(jsonEncode(data));');
    b.writeln('    }');
    b.writeln('  }');
    b.writeln();
    b.writeln('  /// Closes the connection and stops heartbeats/reconnection.');
    b.writeln('  Future<void> disconnect() async {');
    b.writeln('    _connected = false;');
    b.writeln('    _stopHeartbeat();');
    b.writeln('    _reconnectCount = 0;');
    b.writeln('    _lastUrl = null;');
    b.writeln('    await _subscription?.cancel();');
    b.writeln('    _subscription = null;');
    if (channel) {
      b.writeln('    await _socket?.sink.close();');
    } else {
      b.writeln('    await _socket?.close();');
    }
    b.writeln('    _socket = null;');
    b.writeln("    _status.add('disconnected');");
    b.writeln('  }');
    b.writeln('}');
    return b.toString();
  }

  static void _writeOpenSocket(StringBuffer b, SocketServiceConfig config) {
    final channel = config.needsWebSocketChannel;
    b.writeln('  Future<void> _openSocket(String url) async {');
    b.writeln('    try {');
    b.writeln("      _status.add('connecting');");
    if (channel) {
      b.writeln('      final socket = WebSocketChannel.connect(Uri.parse(url));');
      b.writeln('      _socket = socket;');
      b.writeln('      _subscription = socket.stream.listen(');
    } else {
      b.writeln('      final socket = await WebSocket.connect(url);');
      b.writeln('      _socket = socket;');
      b.writeln('      _subscription = socket.listen(');
    }
    b.writeln('        _onData,');
    b.writeln('        onError: _onError,');
    b.writeln('        onDone: _onDone,');
    b.writeln('        cancelOnError: false,');
    b.writeln('      );');
    b.writeln('      _connected = true;');
    b.writeln("      _status.add('connected');");
    b.writeln('      _startHeartbeat();');
    b.writeln('    } catch (e) {');
    b.writeln('      _onError(e);');
    b.writeln('    }');
    b.writeln('  }');
  }
}

/// `chat` -> `Chat`.
String _pascal(String word) =>
    word.isEmpty ? word : word[0].toUpperCase() + word.substring(1);
