import 'dart:io';
import 'package:path/path.dart' as p;

import 'package:ninjadev/src/services/git_service.dart';
import 'package:mason_logger/mason_logger.dart';

class GitGenerator {
  final Logger _logger;
  GitGenerator(this._logger);
  Future<void> generate(String projectPath) async {
    final gitService = GitService(_logger);
    if (!await gitService.isGitInstalled()) {
      _logger.warn('Git is not installed. Skipping git initialization.');
      return;
    }
    await gitService.init(projectPath);
    const gitignore = '''# Flutter
.dart_tool/
.packages
build/
*.iml
.idea/
.vscode/
.metadata
*.lock
*.log
!.packages
# Android
*.apk
*.aab
android/.gradle/
android/gradle/wrapper/gradle-wrapper.jar
android/local.properties
# iOS
ios/Pods/
ios/.symlinks/
ios/Flutter/Flutter.framework
ios/Flutter/Flutter.podspec
ios/Runner.xcworkspace
ios/Flutter/App.framework
# macOS
macos/Pods/
macos/.symlinks/
macos/Runner.xcworkspace
# Web
web/fonts/
# Windows
windows/runner/flutter_windows.dll
windows/runner/FlutterEmbedder.dll
windows/runner/flutter_windows.exe
# Linux
linux/flutter/ephemeral
# Environment
.env
.env.local
.env.dev
.env.prod
# IDE
*.swp
*.swo
*~
# OS
.DS_Store
Thumbs.db
# Coverage
coverage/
# Testing
test_reports/
# NinjaDev
.ninjadev/
''';
    await File(p.join(projectPath, '.gitignore')).writeAsString(gitignore);
    _logger.success('.gitignore created');
    await gitService.stageAndCommit(
      projectPath,
      message: 'Initial commit: Flutter project generated by NinjaDev',
    );
  }
}
